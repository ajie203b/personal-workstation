import { expect, it } from 'vitest'
import { computeLatex } from './compute'
it('不同长度、质量和时间单位可以离线相加和换算', () => {
  expect(computeLatex('2m+30cm=').text).toBe('2.3 m')
  expect(computeLatex('1kg+500g=').text).toBe('1.5 kg')
  expect(computeLatex('5km→m').text).toBe('5000 m')
  expect(computeLatex('2小时+30分钟=').text).toBe('2.5 小时')
})
it('不兼容的单位提示错误，普通代数不误判为单位', () => {
  expect(computeLatex('2m+3kg=').kind).toBe('error')
  expect(computeLatex('2m+1=').kind).not.toBe('error')
  expect(computeLatex('5km→kg').kind).toBe('error')
})

it('支持 LaTeX 单位写法、大小写、温度、面积、体积、存储、速度及标量乘除', () => {
  expect(computeLatex('5\\mathrm{km}\\to\\mathrm{m}').text).toBe('5000 m')
  expect(computeLatex('2\\text{ m}+30\\text{ cm}=').text).toBe('2.3 m')
  expect(computeLatex('5KM\\to M').text).toBe('5000 m')
  expect(computeLatex('2M+30CM=').text).toBe('2.3 m')
  expect(computeLatex('100^{\\circ}C\\to^{\\circ}F').text).toBe('212 °F')
  expect(computeLatex('32°F→°C').text).toBe('0 °C')
  expect(computeLatex('0°C→K').text).toBe('273.15 K')
  expect(computeLatex('1m²→cm²').text).toBe('10000 cm²')
  expect(computeLatex('2m^2+5000cm^2=').text).toBe('2.5 m²')
  expect(computeLatex('2L+500mL=').text).toBe('2.5 L')
  expect(computeLatex('2GB+512MB=').text).toBe('2.5 GB')
  expect(computeLatex('1TB→GB').text).toBe('1024 GB')
  expect(computeLatex('72km/h→m/s').text).toBe('20 m/s')
  expect(computeLatex('10m/s+36km/h=').text).toBe('20 m/s')
  expect(computeLatex('2m * 3 =').text).toBe('6 m')
  expect(computeLatex('6m / 2 =').text).toBe('3 m')
  expect(computeLatex('1km / 200m =').text).toBe('5')
})

it('支持等号目标单位换算、复合单位连写及中国市制/常用物理单位', () => {
  expect(computeLatex('5km=m').text).toBe('5000 m')
  expect(computeLatex('100°C=°F').text).toBe('212 °F')
  expect(computeLatex('2小时30分钟=').text).toBe('2.5 小时')
  expect(computeLatex('1m50cm=').text).toBe('1.5 m')
  expect(computeLatex('2kg→斤').text).toBe('4 斤')
  expect(computeLatex('1公顷→亩').text).toBe('15 亩')
  expect(computeLatex('1kWh→kJ').text).toBe('3600 kJ')
  expect(computeLatex('1MPa→kPa').text).toBe('1000 kPa')
  expect(computeLatex('2.4GHz→MHz').text).toBe('2400 MHz')
})
