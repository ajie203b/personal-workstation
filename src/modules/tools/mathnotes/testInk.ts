/**
 * 单测用的「合成手写」：用折线画几个常见字符，按字宽排成一行。
 * 只用于测试聚类 / 等号检测 / 识别管线，不进业务代码路径。
 */
import type { InkPoint, Stroke } from './types'

type Poly = [number, number][]

/** 单位方框（宽 0.6、高 1，y 向下）里的字形；每个字符若干笔 */
const GLYPHS: Record<string, Poly[]> = {
  '0': [[[0.3, 0], [0.05, 0.2], [0, 0.5], [0.05, 0.8], [0.3, 1], [0.55, 0.8], [0.6, 0.5], [0.55, 0.2], [0.3, 0]]],
  '1': [[[0.15, 0.2], [0.35, 0], [0.35, 1]]],
  '2': [[[0.05, 0.25], [0.2, 0.03], [0.4, 0.02], [0.55, 0.2], [0.5, 0.45], [0.05, 1], [0.6, 1]]],
  '3': [[[0.05, 0.1], [0.3, 0], [0.55, 0.15], [0.5, 0.4], [0.25, 0.5], [0.55, 0.62], [0.58, 0.85], [0.3, 1], [0.03, 0.9]]],
  '4': [[[0.45, 1], [0.45, 0], [0, 0.7], [0.6, 0.7]]],
  '5': [[[0.55, 0], [0.1, 0], [0.05, 0.45], [0.35, 0.4], [0.58, 0.6], [0.5, 0.92], [0.25, 1], [0.03, 0.9]]],
  '6': [[[0.5, 0.05], [0.2, 0.15], [0.03, 0.55], [0.1, 0.92], [0.35, 1], [0.55, 0.85], [0.52, 0.6], [0.3, 0.5], [0.05, 0.62]]],
  '7': [[[0, 0], [0.6, 0], [0.2, 1]]],
  '8': [[[0.3, 0.5], [0.08, 0.3], [0.15, 0.05], [0.45, 0.05], [0.52, 0.3], [0.3, 0.5], [0.05, 0.72], [0.15, 0.97], [0.45, 0.97], [0.55, 0.72], [0.3, 0.5]]],
  '9': [[[0.55, 0.35], [0.35, 0.5], [0.08, 0.4], [0.1, 0.08], [0.4, 0], [0.55, 0.2], [0.5, 1]]],
  '+': [[[0.05, 0.55], [0.55, 0.55]], [[0.3, 0.3], [0.3, 0.8]]],
  '-': [[[0.05, 0.55], [0.55, 0.55]]],
  '=': [[[0.05, 0.45], [0.55, 0.45]], [[0.05, 0.7], [0.55, 0.7]]],
  x: [[[0.05, 0.35], [0.55, 1]], [[0.55, 0.35], [0.05, 1]]],
  '(': [[[0.45, 0], [0.15, 0.3], [0.1, 0.6], [0.45, 1.05]]],
  ')': [[[0.15, 0], [0.45, 0.3], [0.5, 0.6], [0.15, 1.05]]],
}

let seq = 0

/** 折线 → 插值后的笔画（每段插几个点，模拟真实采样） */
function polyToStroke(poly: Poly, ox: number, oy: number, size: number, idPrefix: string): Stroke {
  const points: InkPoint[] = []
  let t = 0
  for (let i = 0; i < poly.length; i++) {
    const [x, y] = poly[i]
    if (i > 0) {
      const [px, py] = poly[i - 1]
      for (let k = 1; k <= 6; k++) {
        const f = k / 6
        points.push({ x: ox + (px + (x - px) * f) * size, y: oy + (py + (y - py) * f) * size, p: 0.5, t: (t += 8) })
      }
    } else points.push({ x: ox + x * size, y: oy + y * size, p: 0.5, t: (t += 8) })
  }
  return { id: `${idPrefix}${String(seq++).padStart(4, '0')}`, points, width: 3 }
}

/** 把一串字符写成一行笔画；返回笔画与下一个字符的 x */
export function writeText(text: string, ox: number, oy: number, size = 40, idPrefix = 's'): Stroke[] {
  const strokes: Stroke[] = []
  let x = ox
  for (const ch of text) {
    if (ch === ' ') {
      x += size * 0.4
      continue
    }
    const glyph = GLYPHS[ch]
    if (!glyph) throw new Error(`testInk 没有字形：${ch}`)
    for (const poly of glyph) strokes.push(polyToStroke(poly, x, oy, size, idPrefix))
    x += size * 0.8
  }
  return strokes
}
