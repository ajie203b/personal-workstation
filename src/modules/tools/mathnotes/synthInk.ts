function polyToStroke(poly: Poly, ox: number, oy: number, size: number, width: number, color?: string): Stroke {
  const points: InkPoint[] = []
  let t = Date.now()
  for (let i = 0; i < poly.length; i++) {
    const [x, y] = poly[i]
    if (i > 0) {
      const [px, py] = poly[i - 1]
      for (let k = 1; k <= 4; k++) {
        const f = k / 4
        points.push({ x: ox + (px + (x - px) * f) * size, y: oy + (py + (y - py) * f) * size, p: 0.5, t: (t += 6) })
      }
    } else {
      points.push({ x: ox + x * size, y: oy + y * size, p: 0.5, t: (t += 6) })
    }
  }
  return { id: `${Date.now().toString(36)}-${uid().slice(0, 8)}`, points, width, ...(color ? { color } : {}) }
}

/** 把键盘输入的算式简化为可手绘显示的短文本并生成合成笔画；未知符号以简约框线替代 */
export function synthFormulaStrokes(
  rawText: string,
  ox: number,
  oy: number,
  size = 36,
  width = 2.6,
  color?: string,
): Stroke[] {
  const clean = rawText
    .replace(/\\times/g, '*')
    .replace(/\\div/g, '/')
    .replace(/\\cdot/g, '*')
    .replace(/\\frac\{([^{}]+)\}\{([^{}]+)\}/g, '($1)/($2)')
    .replace(/\\sqrt\{([^{}]+)\}/g, '($1)')
    .replace(/\\[a-zA-Z]+/g, '')
    .replace(/[{}]/g, '')
    .replace(/×/g, '*')
    .replace(/÷/g, '/')
    .replace(/−/g, '-')
    .replace(/＝/g, '=')
    .replace(/\s+/g, '')
    .slice(0, 18) || '1+1='

  const strokes: Stroke[] = []
  let x = ox
  let y = oy
  for (const ch of clean) {
    if (ch === '\n') {
      x = ox
      y += size * 1.4
      continue
    }
    const lower = ch.toLowerCase()
    const glyph = GLYPHS[ch] ?? GLYPHS[lower] ?? (/[a-zA-Z]/.test(ch) ? [[[0.1, 0.3], [0.5, 0.3]], [[0.3, 0.3], [0.3, 0.95]]] : [[[0.1, 0.55], [0.5, 0.55]]])
    for (const poly of glyph) strokes.push(polyToStroke(poly, x, y, size, width, color))
    x += size * 0.72
  }
  return strokes
}
